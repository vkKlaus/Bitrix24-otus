<?php
/**
 * Скрипт проверки соответствия ID инфоблока коду 'booking'
 * 
 * Назначение: Проверяет, является ли переданный инфоблок инфоблоком бронирования (booking)
 * Функции:
 *   1. Защита от CSRF-атак через проверку сессии Bitrix
 *   2. Получение ID инфоблока из POST-запроса
 *   3. Поиск инфоблока с символьным кодом 'booking' в базе данных
 *   4. Сравнение переданного ID с ID инфоблока бронирования
 *   5. Возврат результата в формате JSON
 * 
 * Использование: Вызывается через AJAX POST-запрос с параметром iblock_id
 * Возвращает: {"is_booking": true/false}
 */

// Подключаем пролог Bitrix - загружает ядро системы, инициализирует сессию, подключает базу данных
// DOCUMENT_ROOT - константа с абсолютным путем к корню сайта
// prolog_before.php - служебный файл, который готовит среду выполнения без подключения шаблона сайта
require($_SERVER["DOCUMENT_ROOT"] . "/bitrix/modules/main/include/prolog_before.php");

// Устанавливаем HTTP-заголовок Content-Type в значение application/json
// Это сообщает браузеру, что сервер возвращает данные в формате JSON, а не HTML
// Браузер будет обрабатывать ответ как JavaScript-объект, а не как веб-страницу
header('Content-Type: application/json');

// Проверяем валидность сессии Bitrix для защиты от CSRF-атак (межсайтовой подделки запросов)
// check_bitrix_sessid() - функция ядра Bitrix, которая проверяет наличие и корректность сессионного идентификатора
// Если проверка не пройдена (например, запрос сделан без сессии или с поддельной сессией)
if (!check_bitrix_sessid()) {
    // Функция json_encode() преобразует PHP-массив в строку формата JSON
    // Возвращаем массив с ключом is_booking и значением false - доступ запрещен
    echo json_encode(['is_booking' => false]);
    // Функция die() немедленно прекращает выполнение скрипта
    // Предотвращает выполнение остального кода при невалидной сессии
    die();
}

// Получаем ID инфоблока из POST-данных и преобразуем в целое число
// $_POST - суперглобальный массив PHP, содержащий данные, отправленные методом POST
// Оператор ?? (null coalescing) возвращает левый операнд, если он существует и не равен null, иначе правый (0)
// intval() - функция PHP, которая преобразует значение в целое число (integer), отсекая дробную часть и строки
// Это защита от SQL-инъекций и некорректных данных - гарантируем, что $iblockId будет числом
$iblockId = intval($_POST['iblock_id'] ?? 0);

// Обращаемся к ORM (Object-Relational Mapping) таблице инфоблоков Bitrix
// \Bitrix\Iblock\IblockTable - класс ORM для работы с таблицей b_iblock в базе данных
// Метод getRow() выполняет SELECT-запрос к базе данных и возвращает одну строку результата
// Принимает массив параметров для построения SQL-запроса
$booking = \Bitrix\Iblock\IblockTable::getRow([
    // Ключ 'select' определяет, какие поля таблицы нужно выбрать (SELECT в SQL)
    // Указываем массив с полем 'ID' - получим только идентификатор инфоблока
    // Это оптимизирует запрос, не выбирая лишние данные
    'select' => ['ID'],
    // Ключ 'filter' определяет условия выборки (WHERE в SQL)
    // '=CODE' означает строгое равенство поля CODE значению 'booking'
    // Знак '=' перед CODE указывает на точное совпадение (не LIKE, не частичное совпадение)
    // Ищем инфоблок с символьным кодом 'booking' - это системный код для инфоблока бронирований
    'filter' => ['=CODE' => 'booking']
]);

// Выводим результат работы скрипта в формате JSON
// json_encode() преобразует PHP-массив в JSON-строку для передачи клиенту (JavaScript)
echo json_encode([
    // Ключ is_booking содержит результат проверки
    // Логическое выражение использует оператор && (логическое И)
    // Сначала проверяется $booking - если getRow() вернул null (инфоблок не найден), результат false
    // Если $booking существует, сравниваем $booking['ID'] с $iblockId через оператор == (нестрогое равенство)
    // Оператор == сравнивает значения после приведения типов (например, '5' == 5 вернет true)
    // Если оба условия истинны - возвращаем true (переданный инфоблок является booking), иначе false
    'is_booking' => $booking && $booking['ID'] == $iblockId
]);