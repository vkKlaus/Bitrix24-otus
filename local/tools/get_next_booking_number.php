<?php
/**
 * Скрипт для генерации следующего номера бронирования
 * 
 * Назначение: Этот скрипт используется в системе 1С-Битрикс для автоматического
 * получения следующего порядкового номера при создании новой записи бронирования.
 * 
 * Функции:
 * - Проверяет авторизацию пользователя и CSRF-токен сессии
 * - Проверяет, что запрашиваемый инфоблок является инфоблоком бронирований (код "booking")
 * - Находит максимальный ID элемента в указанном инфоблоке
 * - Возвращает следующий номер (max_id + 1) в формате JSON
 * 
 * Использование: Вызывается через AJAX POST-запрос с параметром iblock_id
 * Возвращает: JSON с полями success, is_booking, number
 */

// Подключаем загрузчик ядра 1С-Битрикс без стандартного шаблона сайта
// $_SERVER["DOCUMENT_ROOT"] содержит абсолютный путь к корню сайта на сервере
// prolog_before.php инициализирует ядро Битрикса, загружает все модули и настройки
// без подключения header.php и footer.php шаблона сайта (нужно для AJAX-запросов)
require($_SERVER["DOCUMENT_ROOT"] . "/bitrix/modules/main/include/prolog_before.php");

// Устанавливаем HTTP-заголовок Content-Type для ответа в формате JSON с кодировкой UTF-8
// header() - функция PHP для отправки HTTP-заголовков клиенту (браузеру)
// Content-Type: application/json указывает браузеру, что ответ содержит данные в формате JSON
// charset=utf-8 гарантирует правильное отображение кириллических символов
header('Content-Type: application/json; charset=utf-8');

// Импортируем (подключаем) класс Loader из пространства имен Bitrix\Main
// use - ключевое слово PHP для импорта классов из пространств имен (namespaces)
// Bitrix\Main\Loader - класс для загрузки модулей системы Битрикс
use Bitrix\Main\Loader;

// Импортируем класс ElementTable из модуля инфоблоков (iblock)
// ElementTable - ORM-класс (Object-Relational Mapping) для работы с элементами инфоблоков
// Позволяет выполнять SQL-запросы к таблице b_iblock_element через объектный интерфейс
use Bitrix\Iblock\ElementTable;

// Импортируем класс IblockTable из модуля инфоблоков
// IblockTable - ORM-класс для работы с инфоблоками (структурами данных в Битрикс)
// Позволяет получать информацию о самих инфоблоках (ID, код, название и т.д.)
use Bitrix\Iblock\IblockTable;

// Проверяем валидность идентификатора сессии Битрикс (CSRF-защита)
// check_bitrix_sessid() - функция Битрикса, проверяющая токен сессии из $_REQUEST['sessid']
// Защищает от CSRF-атак (межсайтовая подделка запроса) - злоумышленник не может подделать sessid
// Возвращает true если сессия валидна, false если нет
if (!check_bitrix_sessid()) {
    
    // Преобразуем PHP-массив в JSON-строку функцией json_encode()
    // ['success' => false] - ассоциативный массив с одним ключом success и значением false
    // echo выводит строку в буфер вывода, которая уходит клиенту в HTTP-ответе
    echo json_encode(['success' => false]);
    
    // die() или exit() - немедленно прекращает выполнение скрипта
    // Предотвращает выполнение остального кода при невалидной сессии
    die();
}

// Объявляем глобальную переменную $USER - объект текущего авторизованного пользователя
// global - ключевое слово PHP для доступа к переменным из глобальной области видимости
// $USER создается ядром Битрикс при инициализации в prolog_before.php
global $USER;

// Проверяем, авторизован ли текущий пользователь в системе
// IsAuthorized() - метод объекта CUser, возвращает true если пользователь вошел в систему
// ! - оператор логического НЕ (NOT), инвертирует результат
// Если пользователь не авторизован (гость), условие истинно и выполняется блок
if (!$USER->IsAuthorized()) {
    
    // Выводим JSON с ошибкой: операция требует авторизации
    // ['success' => false] - массив с ключом success и булевым значением false
    echo json_encode(['success' => false]);
    
    // Прерываем выполнение скрипта, так как неавторизованный доступ запрещен
    die();
}

// Получаем ID инфоблока из POST-параметров запроса и приводим к целому числу
// $_POST - суперглобальный массив PHP с данными, отправленными методом POST
// $_POST['iblock_id'] ?? 0 - оператор нулевого коалесцента (PHP 7+), возвращает 0 если ключ не существует или null
// intval() - функция PHP, преобразующая значение в целое число (integer), отбрасывает дробную часть
$iblockId = intval($_POST['iblock_id'] ?? 0);

// Проверяем, что полученный ID инфоблока является положительным числом
// intval() может вернуть 0 если передана нечисловая строка или пустое значение
// <= - оператор "меньше или равно", проверяем что число не положительное (0 или отрицательное)
if ($iblockId <= 0) {
    
    // Возвращаем ошибку: невалидный ID инфоблока
    echo json_encode(['success' => false]);
    
    // Останавливаем выполнение скрипта
    die();
}

// Подключаем модуль инфоблоков (iblock) ядра Битрикс
// Loader::includeModule() - статический метод класса Loader для подключения модулей
// 'iblock' - символьный код модуля инфоблоков (информационных блоков)
// Модуль нужен для работы с ElementTable и IblockTable, иначе классы не загрузятся
// Возвращает true при успехе, выбрасывает исключение при ошибке
Loader::includeModule('iblock');

// Получаем информацию об инфоблоке по его ID для проверки кода
// IblockTable::getRow() - статический метод ORM для получения одной строки из БД
// Принимает массив параметров с ключами 'select' (какие поля выбрать) и 'filter' (условия отбора)
$iblock = IblockTable::getRow([
    
    // 'select' - определяет какие колонки таблицы выбрать из базы данных
    // Массив с названиями полей: ID (идентификатор инфоблока) и CODE (символьный код)
    'select' => ['ID', 'CODE'],
    
    // 'filter' - условия фильтрации WHERE в SQL-запросе
    // ['ID' => $iblockId] - ассоциативный массив: выбираем строку где поле ID равно $iblockId
    'filter' => ['ID' => $iblockId]
]);

// Проверяем, найден ли инфоблок и имеет ли он код "booking"
// !$iblock - проверяем что getRow() вернул null (инфоблок не найден по ID)
// || - оператор логического ИЛИ (OR), выполняется если хотя бы одно условие истинно
// $iblock['CODE'] !== 'booking' - проверяем что символьный код инфоблока НЕ равен строке 'booking'
// !== - строгое неравенство (проверяет и значение, и тип данных)
if (!$iblock || $iblock['CODE'] !== 'booking') {
    
    // Возвращаем успешный ответ, но указываем что это не инфоблок бронирований
    // 'success' => true - операция выполнена успешно (проверка прошла)
    // 'is_booking' => false - флаг что инфоблок не является инфоблоком бронирований
    echo json_encode(['success' => true, 'is_booking' => false]);
    
    // Завершаем работу скрипта, дальнейшая обработка не требуется
    die();
}

// Получаем максимальный ID элемента в указанном инфоблоке
// ElementTable::getRow() - ORM-запрос для получения одной строки с агрегатной функцией MAX
// Используем агрегатную функцию SQL MAX() для нахождения наибольшего значения ID
$row = ElementTable::getRow([
    
    // 'select' - определяем вычисляемое поле MAX_ID с агрегатной функцией
    // ElementTable::query() - создает объект Query для построения сложных запросов
    // ->expr('MAX', 'ID') - создает SQL выражение MAX(ID) для вычисления максимума
    // 'MAX_ID' - псевдоним (alias) для результата агрегатной функции в выборке
    'select' => ['MAX_ID' => ElementTable::query()->expr('MAX', 'ID')],
    
    // 'filter' - условие отбора: только элементы из указанного инфоблока
    // IBLOCK_ID - поле в таблице элементов, связывающее элемент с инфоблоком
    'filter' => ['IBLOCK_ID' => $iblockId]
]);

// Извлекаем максимальный ID из результата запроса и приводим к целому числу
// $row['MAX_ID'] ?? 0 - оператор нулевого коалесценции, если MAX_ID нет (null), используем 0
// intval() - преобразуем в целое число, на случай если БД вернула строку
$maxId = intval($row['MAX_ID'] ?? 0);

// Формируем и отправляем финальный JSON-ответ с результатом работы скрипта
// json_encode() - преобразует ассоциативный массив в JSON-строку
// [
//     'success' => true - операция выполнена успешно
//     'is_booking' => true - подтверждаем что это инфоблок бронирований
//     'number' => $maxId + 1 - следующий номер (максимальный + 1)
// ]
// + - арифметический оператор сложения, увеличиваем максимальный ID на 1
echo json_encode([
    'success' => true,
    'is_booking' => true,
    'number' => $maxId + 1
]);