<?php
/**
 * СКРИПТ: Получение списка врачей по ID специальности
 * 
 * НАЗНАЧЕНИЕ:
 * Этот скрипт является AJAX-обработчиком (API endpoint) для динамической подгрузки
 * списка врачей на веб-форму. Когда пользователь выбирает специальность (например,
 * "Кардиолог", "Терапевт") в выпадающем списке, JavaScript на фронтенде отправляет
 * запрос к этому скрипту, передавая ID выбранной специальности через GET-параметр.
 * 
 * ФУНКЦИОНАЛЬНОСТЬ:
 * 1. Принимает GET-параметр SPECIALTY_ID (целое число)
 * 2. Проверяет валидность входных данных (ID > 0)
 * 3. Загружает модуль инфоблоков Bitrix (iblock) для работы с базой данных
 * 4. Выполняет SQL-запрос к таблице элементов инфоблока (база данных)
 * 5. Фильтрует врачей: активные элементы с указанной специальностью
 * 6. Сортирует результат по алфавиту (по имени врача)
 * 7. Возвращает данные в формате JSON: массив объектов {id, name}
 * 
 * ПРИМЕР ИСПОЛЬЗОВАНИЯ НА ФРОНТЕНДЕ:
 * fetch('/local/tools/get_specialty_doctors.php?SPECIALTY_ID=5')
 *   .then(response => response.json())
 *   .then(doctors => {
 *     // doctors = [{id: 10, name: "Иванов И.И."}, {id: 15, name: "Петров П.П."}]
 *   });
 * 
 * ТРЕБОВАНИЯ:
 * - Константа DOCTORS_IBLOCK_ID должна быть определена в init.php или dbconn.php
 * - Модуль iblock должен быть установлен в системе 1С-Битрикс
 */

// Подключаем пролог (заголовочную часть) ядра Bitrix без визуальной части сайта
// DOCUMENT_ROOT - абсолютный путь к корню сайта на сервере (например, /var/www/html)
// prolog_before.php инициализирует ядро CMS, подключает БД, загружает конфигурацию
// но не выводит шапку сайта (header.php), что критично для AJAX-скриптов
require($_SERVER["DOCUMENT_ROOT"]."/bitrix/modules/main/include/prolog_before.php");

// Устанавливаем HTTP-заголовок ответа, указывая браузеру/JS, что содержимое - JSON
// Content-Type: application/json - стандарт MIME-типа для данных в формате JSON
// Это позволяет фронтенду (JavaScript fetch/axios/jQuery.ajax) автоматически распарсить ответ
header('Content-Type: application/json');

// Получаем значение GET-параметра SPECIALTY_ID из URL (например, ?SPECIALTY_ID=5)
// Оператор ?? (null coalescing, PHP 7+) возвращает 0, если параметр не передан или null
// intval() - приводит значение к целому числу (integer), отсекая дробную часть
// Это защита от SQL-инъекций и XSS: строка "5abc" станет числом 5, "abc" станет 0
$specialtyId = intval($_GET['SPECIALTY_ID'] ?? 0);

// Инициализируем пустой массив для накопления результатов
// $result будет содержать финальный список врачей перед кодированием в JSON
$result = [];

// Условие: выполняем поиск только если specialtyId > 0 (валидный ID) 
// И если успешно подключился модуль инфоблоков (iblock) Bitrix
// Bitrix\Main\Loader::includeModule('iblock') возвращает true при успехе, false при ошибке
// Это проверка: модуль установлен? есть права доступа? не заблокирован лицензией?
if ($specialtyId > 0 && Bitrix\Main\Loader::includeModule('iblock')) {
    
    // Создаем объект класса CIBlockElement - основной класс для работы с элементами инфоблоков
    // CIBlockElement::GetList() - метод получения списка элементов из БД (аналог SELECT в SQL)
    // Параметры метода (в порядке следования):
    // 1. $arOrder - массив сортировки: ['NAME' => 'ASC'] сортирует по полю NAME (имя врача) по возрастанию (A-Z)
    // 2. $arFilter - массив фильтрации условий WHERE в SQL-запросе:
    //    - IBLOCK_ID => DOCTORS_IBLOCK_ID: ищем только в инфоблоке врачей (константа с ID инфоблока)
    //    - ACTIVE => 'Y': только активные (опубликованные) элементы, не помеченные как удаленные
    //    - PROPERTY_SPECIALIZATION_ID => $specialtyId: свойство элемента (поле) должно содержать наш ID специальности
    // 3. $arGroupBy - false: группировка отключена (не используем GROUP BY)
    // 4. $arNavStartParams - false: без постраничной навигации (возвращаем все записи)
    // 5. $arSelectFields - массив полей для выборки: достаем только ID (уникальный идентификатор) и NAME (ФИО врача)
    //    Это оптимизация: не тащим лишние данные из БД (описания, фото, даты)
    $rs = CIBlockElement::GetList(
        ['NAME' => 'ASC'],
        [
            'IBLOCK_ID' => DOCTORS_IBLOCK_ID,
            'ACTIVE' => 'Y',
            'PROPERTY_SPECIALTY_ID' => $specialtyId
        ],
        false,
        false,
        ['ID', 'NAME']
    );
    
    // Цикл while проходит по всем записям результата выборки
    // Метод Fetch() извлекает текущую строку из результата запроса как ассоциативный массив
    // и перемещает внутренний указатель на следующую запись
    // Когда записи заканчиваются, Fetch() возвращает false, цикл прерывается
    // $doc - временная переменная, содержит данные одного врача на каждой итерации
    // Структура $doc: ['ID' => '123', 'NAME' => 'Иванов Иван Иванович', ...]
    while ($doc = $rs->Fetch()) {
        
        // Добавляем в массив $result новый элемент (ассоциативный массив)
        // Оператор [] = ... - синтаксис добавления элемента в конец массива (push)
        // Формируем структуру данных для JSON: 
        // 'id' => $doc['ID'] - приводим ID к числу (хотя в БД обычно строка, для JSON лучше число)
        // 'name' => $doc['NAME'] - ФИО врача из поля NAME инфоблока
        // Итоговый элемент: ['id' => 123, 'name' => 'Иванов И.И.']
        $result[] = ['id' => $doc['ID'], 'name' => $doc['NAME']];
    }
}

// Кодируем массив PHP в строку формата JSON для отправки клиенту
// json_encode() преобразует PHP-массив/объект в JSON-строку
// Если $result пуст (нет врачей или неверный specialtyId), вернет [] (пустой массив JSON)
// Если нашли врачей, вернет [{"id":"10","name":"Иванов"},{"id":"15","name":"Петров"}]
// echo выводит результат в HTTP-ответ, который получает JavaScript на фронтенде
echo json_encode($result);