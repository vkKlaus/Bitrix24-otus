<?php
// =============================================================================
// СКРИПТ: Получение специализаций врача
// =============================================================================
// НАЗНАЧЕНИЕ: 
// Этот скрипт является API-эндпоинтом (точкой входа для AJAX-запросов), 
// который возвращает список медицинских специализаций конкретного врача 
// в формате JSON. Используется, например, в формах записи на приём,
// где нужно показать, какие направления лечения доступны у выбранного доктора.
//
// ФУНКЦИИ:
// 1. Принимает ID врача через GET-параметр DOCTOR_ID
// 2. Загружает данные из информационного блока (инфоблока) "Врачи"
// 3. Находит связанные специализации через свойство SPECIALIZATION_ID
// 4. Для каждой специализации получает длительность приёма (RECEPTION_DURATION)
// 5. Возвращает массив специализаций с ID, названием и длительностью в JSON
// =============================================================================

// Подключаем служебный файл "prolog_before.php" из ядра 1С-Битрикс
// Этот файл инициализирует минимальное окружение CMS: подключает константы,
// автозагрузчик классов, настройки базы данных и сессию пользователя.
// DOCUMENT_ROOT - это абсолютный путь к корню сайта на сервере (например, /var/www/html)
require($_SERVER["DOCUMENT_ROOT"]."/bitrix/modules/main/include/prolog_before.php");

// Устанавливаем HTTP-заголовок Content-Type со значением application/json
// Этот заголовок сообщает браузеру/клиенту, что ответ сервера будет в формате JSON,
// а не HTML. Это важно для JavaScript, который ожидает распарсить JSON-ответ.
header('Content-Type: application/json');

// Объявляем переменную $doctorId и присваиваем ей результат работы функции intval()
// intval() преобразует значение в целое число (integer), отбрасывая дробную часть
// и защищая от SQL-инъекций (хотя здесь используется ORM, всё равно хорошая практика)
// $_GET - это суперглобальный массив PHP, содержащий параметры URL (query string)
// Оператор ?? (null coalescing operator, PHP 7+) возвращает левое значение, 
// если оно существует и не null, иначе правое (0). Защита от ошибки, если DOCTOR_ID не передан.
$doctorId = intval($_GET['DOCTOR_ID'] ?? 0);

// Инициализируем пустой массив $result, который будет накапливать данные специализаций
// Этот массив станет финальным JSON-ответом. Если ничего не найдено, вернётся [] (пустой массив)
$result = [];

// Начинаем условную конструкцию if для проверки двух условий:
// 1. $doctorId > 0 - проверяем, что ID врача валидный (положительное число)
// 2. Bitrix\Main\Loader::includeModule('iblock') - подключаем модуль "Информационные блоки"
//    Этот модуль нужен для работы с CIBlockElement - классом для операций с элементами инфоблоков
//    Если модуль не подключится (например, отключен в админке), метод вернёт false
if ($doctorId > 0 && Bitrix\Main\Loader::includeModule('iblock')) {
    
    // Вызываем статический метод GetProperty() класса CIBlockElement
    // Этот метод получает значения свойств элемента инфоблока без загрузки самого элемента
    // Параметры:
    //   DOCTORS_IBLOCK_ID - константа с ID инфоблока "Врачи" (должна быть определена ранее)
    //   $doctorId - ID конкретного врача
    //   [] - массив фильтров (пустой, без дополнительной фильтрации)
    //   ['CODE' => 'SPECIALIZATION_ID'] - выбираем только свойство с символьным кодом SPECIALIZATION_ID
    //        Это свойство типа "Привязка к элементам" - хранит ID связанных специализаций
    // Метод возвращает объект типа CIBlockResult (результат запроса к БД)
    $rs = CIBlockElement::GetProperty(DOCTORS_IBLOCK_ID, $doctorId, [], ['CODE' => 'SPECIALIZATION_ID']);
    
    // Запускаем цикл while для перебора всех значений свойства SPECIALIZATION_ID
    // Метод Fetch() извлекает следующую строку результата в виде ассоциативного массива
    // и сдвигает внутренний указатель. Когда строки заканчиваются, возвращает false и цикл прекращается.
    // Это нужно, потому что у врача может быть несколько специализаций (множественное свойство)
    while ($prop = $rs->Fetch()) {
        
        // Проверяем, что значение свойства не пустое (не false, не null, не пустая строка, не 0)
        // Если $prop['VALUE'] содержит ID специализации, продолжаем обработку
        if ($prop['VALUE']) {
            
            // Получаем полные данные элемента специализации по его ID
            // CIBlockElement::GetByID() - статический метод для быстрого получения элемента по ID
            // Возвращает объект CIBlockResult, сразу вызываем Fetch() чтобы получить массив данных
            // Результат содержит поля: ID, NAME (название), CODE и другие стандартные поля элемента
            $spec = CIBlockElement::GetByID($prop['VALUE'])->Fetch();
            
            // Проверяем, что элемент специализации существует (не false)
            // Если врач привязан к несуществующей специализации (удалённой), $spec будет false
            if ($spec) {
                
                // Получаем значение свойства RECEPTION_DURATION (длительность приёма в минутах)
                // из инфоблока специализаций (SPECIALTIES_IBLOCK_ID - константа с ID инфоблока)
                // Это свойство хранит, сколько минут длится приём по данной специализации
                // Снова используем GetProperty для конкретного свойства по символьному коду
                $dur = CIBlockElement::GetProperty(SPECIALTIES_IBLOCK_ID, $spec['ID'], [], ['CODE' => 'RECEPTION_DURATION'])->Fetch();
                
                // Добавляем в массив $result ассоциативный массив с данными специализации
                // Оператор [] после переменной массива означает "добавить новый элемент в конец массива"
                // Внутри массива:
                //   'id' => $spec['ID'] - ID специализации (число)
                //   'name' => $spec['NAME'] - Название специализации (строка, например "Терапевт")
                //   'duration' => intval($dur['VALUE']) ?: 15 - длительность приёма:
                //        intval() преобразует в число (если свойство не заполнено, будет 0)
                //        Оператор ?: (элвис-оператор) - если левая часть "ложная" (0, false, null), 
                //        используется правая часть (15 - значение по умолчанию, 15 минут)
                $result[] = [
                    'id' => $spec['ID'],
                    'name' => $spec['NAME'],
                    'duration' => intval($dur['VALUE']) ?: 15
                ];
            }
        }
    }
}

// Преобразуем массив $result в JSON-строку функцией json_encode()
// JSON (JavaScript Object Notation) - текстовый формат обмена данными
// Функция превращает PHP-массив в строку вида [{"id":1,"name":"Терапевт","duration":30},...]
// Эту строку JavaScript на фронтенде может распарсить методом JSON.parse() или получить как объект
echo json_encode($result);