<?php
/**
 * =============================================================================
 * СКРИПТ: BookingHandlers.php
 * =============================================================================
 * 
 * НАЗНАЧЕНИЕ:
 * Данный скрипт является обработчиком событий для системы бронирования 
 * медицинских приёмов в 1С-Битрикс. Он обеспечивает валидацию данных 
 * при создании и обновлении записей на приём к врачу.
 * 
 * ОСНОВНЫЕ ФУНКЦИИ:
 * 1. Проверка обязательных полей (ФИО пациента, врач, специальность, дата/время)
 * 2. Валидация соответствия врача и специальности (врач должен работать по выбранной специальности)
 * 3. Проверка пересечения времени приёма - предотвращает двойное бронирование одного врача
 * 4. Расчёт длительности приёма на основе специальности
 * 5. Формирование понятных сообщений об ошибках для пользователей
 * 
 * ПРИНЦИП РАБОТЫ:
 * Скрипт подключается к событиям ядра Битрикс onBeforeAdd и onBeforeUpdate,
 * которые вызываются ДО сохранения элемента инфоблока. Если валидация не пройдена,
 * сохранение отменяется и пользователю выводится сообщение об ошибке.
 */

// Объявление пространства имён класса. Пространства имён в PHP позволяют организовать код 
// в логические группы и избежать конфликтов имён классов. Здесь класс находится 
// в пространстве Local\CustomProperties, что указывает на его принадлежность к 
// локальным кастомным свойствам/обработчикам проекта.
namespace Local\CustomProperties;

// Подключение класса Loader из ядра Битрикс. Loader используется для подгрузки 
// модулей системы (в данном случае модуля инфоблоков) по требованию.
use Bitrix\Main\Loader;

// Подключение класса Application из ядра Битрикс. Application предоставляет доступ 
// к глобальному контексту приложения, хотя в данном файле напрямую не используется.
use Bitrix\Main\Application;

// Подключение класса ElementTable из модуля инфоблоков. ElementTable - это ORM-класс 
// (Object-Relational Mapping) для работы с элементами инфоблоков через современное API,
// позволяет выполнять запросы к базе данных в объектно-ориентированном стиле.
use Bitrix\Iblock\ElementTable;

// Объявление класса BookingHandlers. Это основной класс обработчика, содержащий 
// статические методы для валидации бронирований. Ключевое слово class создаёт 
// новый тип данных с методами и свойствами.
class BookingHandlers
{
    // Объявление константы класса DOCTOR_PROP_CODE со значением 'DOCTOR'. 
    // Константы - это неизменяемые значения, определяемые на уровне класса.
    // Символьный код свойства инфоблока, хранящего привязку к врачу (ID элемента инфоблока врачей).
    const DOCTOR_PROP_CODE = 'DOCTOR';
    
    // Объявление константы класса SPECIALTY_PROP_CODE со значением 'SPECIALITY'.
    // Символьный код свойства инфоблока, хранящего привязку к специальности (ID элемента инфоблока специальностей).
    const SPECIALTY_PROP_CODE = 'SPECIALITY';
    
    // Объявление константы класса DATETIME_PROP_CODE со значением 'BOOKING_DATETIME'.
    // Символьный код свойства инфоблока, хранящего дату и время приёма в формате строки.
    const DATETIME_PROP_CODE = 'BOOKING_DATETIME';
    
    // Объявление константы класса PATIENT_PROP_CODE со значением 'PATIENT_NAME'.
    // Символьный код свойства инфоблока, хранящего ФИО пациента (текстовое поле).
    const PATIENT_PROP_CODE = 'PATIENT_NAME';

    // Объявление публичного статического метода onBeforeAdd. Метод помечен как public,
    // что делает его доступным извне класса. static означает, что метод принадлежит 
    // классу, а не объекту, и может быть вызван без создания экземпляра класса.
    // Параметр &$arFields передаётся по ссылке (амперсанд &), что позволяет модифицировать 
    // входной массив данных формы внутри метода. Метод вызывается ядром Битрикс 
    // перед добавлением нового элемента инфоблока.
    public static function onBeforeAdd(&$arFields)
    {
        // Условный оператор if проверяет, относится ли текущий элемент к инфоблоку бронирований.
        // BOOKING_IBLOCK_ID - это константа, определённая в другом месте проекта (обычно в init.php),
        // содержащая числовой ID инфоблока записей на приём. Оператор != означает "не равно".
        // Если это не инфоблок бронирований, метод возвращает true, разрешая стандартное сохранение.
        if ($arFields['IBLOCK_ID'] != BOOKING_IBLOCK_ID) return true;
        
        // Вызов приватного статического метода validateBooking для проверки корректности данных.
        // Результат сохраняется в переменной $error. self:: - это способ обращения к статическим 
        // членам текущего класса изнутри.
        $error = self::validateBooking($arFields);
        
        // Условный оператор if проверяет, не равен ли результат валидации логическому true.
        // Если validateBooking вернул строку с ошибкой (а не true), условие выполняется.
        if ($error !== true) {
            // Ключевое слово global объявляет использование глобальной переменной $APPLICATION.
            // $APPLICATION - это глобальный объект приложения Битрикс, содержащий методы для 
            // взаимодействия с ядром системы, включая вывод ошибок.
            global $APPLICATION;
            
            // Вызов метода ThrowException глобального объекта $APPLICATION. Этот метод 
            // регистрирует исключение/ошибку в системе Битрикс, которое будет показано 
            // пользователю в административной панели или на сайте. Параметр $error 
            // содержит текст сообщения об ошибке.
            $APPLICATION->ThrowException($error);
            
            // Возврат логического false. При возврате false из обработчика onBeforeAdd 
            // ядро Битрикс отменяет операцию добавления элемента и выводит зарегистрированную ошибку.
            return false;
        }
        
        // Возврат логического true при успешной валидации. Это разрешает ядру Битрикс 
        // продолжить стандартный процесс сохранения элемента инфоблока.
        return true;
    }

    // Объявление публичного статического метода onBeforeUpdate. Этот метод является 
    // обработчиком события, вызываемого перед обновлением существующего элемента инфоблока.
    // Параметр &$arFields также передаётся по ссылке и содержит новые данные для обновления.
    public static function onBeforeUpdate(&$arFields)
    {
        // Проверка ID инфоблока. Если обновляется элемент не из инфоблока бронирований,
        // метод немедленно возвращает true, разрешая обновление без дополнительных проверок.
        if ($arFields['IBLOCK_ID'] != BOOKING_IBLOCK_ID) return true;
        
        // Условный оператор isset проверяет существование ключа 'PROPERTY_VALUES' в массиве $arFields.
        // При обновлении элемента через API или форму этот ключ содержит массив свойств.
        // Если свойства не передаются (например, обновляется только название), 
        // валидация не требуется и метод возвращает true.
        if (!isset($arFields['PROPERTY_VALUES'])) return true;
        
        // Вызов метода валидации данных бронирования. Логика идентична методу onBeforeAdd.
        $error = self::validateBooking($arFields);
        
        // Проверка результата валидации. Если возвращена строка ошибки (не true),
        // выполняется блок обработки ошибки.
        if ($error !== true) {
            // Обращение к глобальному объекту приложения для регистрации ошибки.
            global $APPLICATION;
            
            // Регистрация исключения с текстом ошибки. Это приведёт к отображению 
            // сообщения пользователю и отмене операции обновления.
            $APPLICATION->ThrowException($error);
            
            // Возврат false отменяет обновление элемента в базе данных.
            return false;
        }
        
        // Возврат true при успешной валидации разрешает продолжение операции обновления.
        return true;
    }

    // Объявление приватного статического метода validateBooking. Модификатор private 
    // делает метод доступным только внутри текущего класса. Это вспомогательный метод,
    // не предназначенный для вызова извне. Он содержит основную логику проверки данных.
    private static function validateBooking(&$arFields)
    {
        // Вызов статического метода includeModule класса Loader. Этот метод подгружает 
        // модуль 'iblock' (инфоблоки) ядра Битрикс, обеспечивая доступ к его API 
        // (классы CIBlockElement, CIBlockProperty и др.). Без этого вызова 
        // последующие обращения к API инфоблоков вызовут ошибку.
        Loader::includeModule('iblock');
        
        // Оператор ?? (null coalescing operator, появился в PHP 7.0) возвращает левый операнд,
        // если он существует и не равен null, иначе - правый операнд (пустой массив).
        // Здесь извлекаются значения свойств из массива данных формы. Если свойства не переданы,
        // используется пустой массив для избежания ошибок при последующем доступе.
        $props = $arFields['PROPERTY_VALUES'] ?? [];
        
        // Вызов приватного метода getPropValue для получения значения свойства "Врач".
        // Метод принимает массив всех свойств и символьный код нужного свойства.
        // Результат - ID элемента инфоблока врачей или null/пустое значение.
        $doctorId = self::getPropValue($props, self::DOCTOR_PROP_CODE);
        
        // Аналогичный вызов для получения ID специальности из свойств формы.
        $specialtyId = self::getPropValue($props, self::SPECIALTY_PROP_CODE);
        
        // Получение строки с датой и временем приёма из свойств формы.
        $dateTime = self::getPropValue($props, self::DATETIME_PROP_CODE);
        
        // Получение ФИО пациента из свойств формы. Это текстовое поле.
        $patientName = self::getPropValue($props, self::PATIENT_PROP_CODE);

        // Получение текущего ID элемента из массива полей. Оператор ?? возвращает 0,
        // если ключ 'ID' отсутствует (что характерно для операции добавления нового элемента).
        // При обновлении $currentId содержит ID существующего элемента, что важно 
        // для исключения его самого из проверки конфликтов времени.
        $currentId = $arFields['ID'] ?? 0;

        // Проверка заполненности поля ФИО пациента. Функция empty() возвращает true,
        // если переменная не существует, равна null, пустой строке, 0, false или пустому массиву.
        // Это обязательное поле для записи на приём.
        if (empty($patientName)) {
            // Возврат строки с сообщением об ошибке. Эта строка будет показана пользователю.
            // return немедленно прерывает выполнение метода, возвращая значение вызывающему коду.
            return 'Элемент не записан. Необходимо указать ФИО пациента';
        }
        
        // Проверка выбора врача. Оператор ! (логическое НЕ) инвертирует значение.
        // Если $doctorId равно null, 0, пустой строке или false, условие выполняется.
        if (!$doctorId) {
            // Возврат сообщения об ошибке при отсутствии выбранного врача.
            return 'Элемент не записан. Необходимо выбрать врача';
        }
        
        // Проверка выбора специальности. Логика аналогична проверке врача.
        if (!$specialtyId) {
            // Возврат сообщения об ошибке при отсутствии специальности.
            return 'Элемент не записан. Необходимо выбрать специальность';
        }
        
        // Проверка указания даты и времени приёма.
        if (!$dateTime) {
            // Возврат сообщения об ошибке при отсутствии даты/времени.
            return 'Элемент не записан. Необходимо указать дату и время';
        }

        // Вызов метода проверки соответствия врача и специальности. Метод проверяет,
        // работает ли выбранный врач по выбранной специальности (связь хранится 
        // в свойствах элемента врача). Оператор ! инвертирует результат: если метод 
        // вернул false (не соответствует), условие выполняется.
        if (!self::checkDoctorSpecialtyMatch($doctorId, $specialtyId)) {
            // Возврат сообщения о несоответствии специальности врачу.
            return 'Элемент не записан. Выбранный врач не работает по данной специальности';
        }

        // Вызов метода проверки конфликта времени. Метод ищет другие записи к этому же врачу,
        // пересекающиеся по времени с текущей записью. Передаются: ID текущего элемента (для исключения
        // из проверки при обновлении), ID врача, дата/время новой записи, ID специальности (для расчёта длительности).
        $conflict = self::checkTimeConflict($currentId, $doctorId, $dateTime, $specialtyId);
        
        // Проверка результата. Если метод вернул не null (а строку с описанием конфликта),
        // значит обнаружено пересечение по времени с существующей записью.
        if ($conflict) {
            // Возврат сообщения о конфликте времени. Сообщение содержит детали 
            // существующей записи (название, время, специальность).
            return $conflict;
        }

        // Возврат логического true при успешном прохождении всех проверок.
        // Это сигнализирует вызывающему коду (onBeforeAdd/onBeforeUpdate), что валидация пройдена.
        return true;
    }

    // Объявление приватного статического метода getPropValue. Метод извлекает значение 
    // свойства из массива свойств формы. Это универсальный метод, обрабатывающий 
    // различные форматы передачи свойств в Битрикс (по коду, по ID, массивы значений).
    private static function getPropValue($props, $code)
    {
        // Проверка прямого доступа по символьному коду свойства. В некоторых случаях 
        // (особенно при работе через API), свойства доступны напрямую по своему коду.
        if (isset($props[$code])) {
            // Получение значения свойства во временную переменную $val.
            $val = is_array($props[$code]) ? reset($props[$code]) : $props[$code];
            
            // Проверка, является ли значение массивом (структура с ключом VALUE часто используется 
            // в сложных свойствах). Если да - извлекается значение по ключу 'VALUE', иначе 
            // возвращается само значение. Оператор ?? возвращает левый операнд, если он существует.
            return is_array($val) ? ($val['VALUE'] ?? $val) : $val;
        }
        
        // Если прямой доступ не сработал, выполняется поиск по ID свойства.
        // Цикл foreach перебирает все элементы массива $props. Ключи массива сохраняются 
        // в $key, значения - в $val.
        foreach ($props as $key => $val) {
            // Проверка, является ли ключ числом (ID свойства всегда числовой).
            // is_numeric возвращает true, если строка содержит число.
            if (!is_numeric($key)) continue;
            
            // Получение данных о свойстве по его ID через API Битрикс.
            // \CIBlockProperty::GetByID($key) возвращает объект результата запроса к БД.
            // Метод Fetch() извлекает первую (и единственную) строку результата в виде массива.
            $prop = \CIBlockProperty::GetByID($key)->Fetch();
            
            // Проверка: свойство найдено ($prop не false) и его символьный код CODE 
            // совпадает с искомым кодом $code.
            if ($prop && $prop['CODE'] == $code) {
                // Аналогичная обработка значения: если массив - берём первый элемент,
                // затем проверяем на вложенный массив со структурой VALUE.
                $v = is_array($val) ? reset($val) : $val;
                return is_array($v) ? ($v['VALUE'] ?? $v) : $v;
            }
        }
        
        // Если свойство не найдено ни по коду, ни по ID, возвращается null.
        // Это сигнализирует об отсутствии значения (например, при обновлении 
        // без изменения свойств, или если свойство не заполнено).
        return null;
    }

    // Объявление приватного статического метода checkDoctorSpecialtyMatch. Метод проверяет,
    // связан ли врач с указанной специальностью через множественное свойство SPECIALIZATION_ID
    // в инфоблоке врачей.
    private static function checkDoctorSpecialtyMatch($doctorId, $specialtyId)
    {
        // Вызов метода GetProperty класса CIBlockElement для получения значений свойства.
        // DOCTORS_IBLOCK_ID - константа с ID инфоблока врачей. $doctorId - ID элемента (врача).
        // Третий параметр (пустой массив) - дополнительные фильтры. Четвёртый параметр 
        // указывает символьный код свойства 'SPECIALIZATION_ID', которое хранит привязку 
        // к специальностям (множественное свойство типа "Привязка к элементам").
        $rs = \CIBlockElement::GetProperty(
            DOCTORS_IBLOCK_ID, 
            $doctorId, 
            [], 
            ['CODE' => 'SPECIALIZATION_ID']
        );
        
        // Цикл while перебирает все значения множественного свойства. Метод Fetch() 
        // извлекает очередную строку результата запроса. Когда данные закончатся, 
        // Fetch() вернёт false и цикл прекратится.
        while ($prop = $rs->Fetch()) {
            // Сравнение значения свойства (ID специальности) с искомым ID.
            // Если найдено совпадение, врач работает по этой специальности.
            if ($prop['VALUE'] == $specialtyId) return true;
        }
        
        // Если цикл завершился без находки совпадений, возвращается false.
        // Это означает, что выбранный врач не работает по указанной специальности.
        return false;
    }

    // Объявление приватного статического метода checkTimeConflict. Это ключевой метод 
    // проверки пересечения времени приёма. Он ищет существующие записи к тому же врачу,
    // которые пересекаются по времени с новой/обновляемой записью.
    private static function checkTimeConflict($currentId, $doctorId, $dateTime, $specialtyId)
    {
        // Получение длительности приёма для выбранной специальности в минутах.
        // Вызов метода getReceptionDuration возвращает число или null. Оператор ?: 
        // (элвис-оператор) возвращает левый операнд, если он существует и не равен null,
        // иначе - правый операнд (15 - стандартная длительность приёма по умолчанию).
        $duration = self::getReceptionDuration($specialtyId) ?: 15;
        
        // Преобразование строки даты/времени в Unix timestamp (количество секунд с 1 января 1970).
        // Функция strtotime парсит строку формата 'd.m.Y H:i:s' или подобные.
        $newStart = strtotime($dateTime);
        
        // Проверка успешности преобразования. Если strtotime не смог распознать формат,
        // он возвращает false. В этом случае возвращается сообщение об ошибке.
        if (!$newStart) return 'Некорректный формат даты/времени';
        
        // Расчёт времени окончания приёма. К начальному времени добавляется длительность,
        // умноженная на 60 (перевод минут в секунды для корректного сложения с Unix timestamp).
        $newEnd = $newStart + ($duration * 60);

        // Вызов метода GetList класса CIBlockElement для получения списка существующих 
        // бронирований. Это мощный метод для выборки элементов с фильтрацией и сортировкой.
        $rs = \CIBlockElement::GetList(
            // Первый параметр - массив сортировки. ['ID' => 'ASC'] означает сортировку 
            // по возрастанию ID (хотя для данной логики порядок не важен).
            ['ID' => 'ASC'],
            
            // Второй параметр - массив фильтра. Определяет условия выборки элементов.
            [
                // Фильтр по ID инфоблока бронирований. BOOKING_IBLOCK_ID - константа проекта.
                'IBLOCK_ID' => BOOKING_IBLOCK_ID,
                
                // Оператор ! означает "не равно". Исключаем текущий элемент из проверки 
                // (важно при обновлении существующей записи, чтобы она не конфликтовала сама с собой).
                '!ID' => $currentId,
                
                // Фильтр по свойству DOCTOR. Выбираем только записи к тому же врачу.
                // Это ключевой момент: проверка идёт только в разрезе врача, а не кабинета или клиники.
                'PROPERTY_DOCTOR' => $doctorId,
            ],
            
            // Третий параметр (false) - группировка результатов. false означает без группировки.
            false,
            
            // Четвёртый параметр (false) - постраничная навигация. false означает выборку всех элементов.
            false,
            
            // Пятый параметр - массив полей для выборки. Указываем минимальный набор 
            // необходимых данных: ID, название, дата/время приёма, специальность.
            ['ID', 'NAME', 'PROPERTY_BOOKING_DATETIME', 'PROPERTY_SPECIALITY']
        );

        // Цикл перебора найденных существующих бронирований.
        while ($booking = $rs->Fetch()) {
            // Проверка наличия даты/времени в найденной записи. Если свойство не заполнено,
            // пропускаем эту запись (continue передаёт управление на следующую итерацию цикла).
            if (empty($booking['PROPERTY_BOOKING_DATETIME_VALUE'])) continue;
            
            // Преобразование даты/времени существующей записи в Unix timestamp.
            $existStart = strtotime($booking['PROPERTY_BOOKING_DATETIME_VALUE']);
            
            // Проверка корректности даты существующей записи. Если формат неверный, пропускаем.
            if (!$existStart) continue;
            
            // Получение ID специальности существующей записи. Это нужно для определения 
            // длительности приёма существующей записи (разные специальности = разное время).
            $existSpecialtyId = $booking['PROPERTY_SPECIALITY_VALUE'];
            
            // Получение длительности приёма для специальности существующей записи.
            // Используется тот же метод с дефолтным значением 15 минут.
            $existDuration = self::getReceptionDuration($existSpecialtyId) ?: 15;
            
            // Расчёт времени окончания существующего приёма.
            $existEnd = $existStart + ($existDuration * 60);

            // Проверка пересечения временных интервалов. Два интервала [newStart, newEnd] 
            // и [existStart, existEnd] пересекаются, если:
            // - новый интервал начинается раньше, чем заканчивается существующий ($newStart < $existEnd)
            // - И новый интервал заканчивается позже, чем начинается существующий ($newEnd > $existStart)
            // Это классическая проверка пересечения отрезков на числовой прямой.
            if ($newStart < $existEnd && $newEnd > $existStart) {
                // Если пересечение обнаружено, формируется детальное сообщение об ошибке.
                // Функция sprintf форматирует строку, подставляя значения переменных вместо плейсхолдеров.
                return sprintf(
                    // Шаблон строки с плейсхолдерами: %s - строка, %s - строка (дата), %s - строка (время), %s - строка.
                    'Элемент не записан. Врач занят! Пересечение с "%s" (%s - %s, специальность: %s)',
                    
                    // Первый аргумент - название существующей записи (обычно ФИО пациента).
                    $booking['NAME'],
                    
                    // Второй аргумент - дата и время начала существующего приёма.
                    // Функция date форматирует Unix timestamp в читаемую строку 'дд.мм.гггг чч:мм'.
                    date('d.m.Y H:i', $existStart),
                    
                    // Третий аргумент - только время окончания (дата не повторяется для краткости).
                    date('H:i', $existEnd),
                    
                    // Четвёртый аргумент - название специальности существующей записи.
                    self::getSpecialtyName($existSpecialtyId)
                );
            }
        }

        // Если цикл завершился без обнаружения пересечений, возвращается null.
        // null сигнализирует об отсутствии конфликтов (в отличие от строки с ошибкой).
        return null;
    }

    // Объявление приватного статического метода getReceptionDuration. Метод получает 
    // длительность приёма (в минутах) для указанной специальности из инфоблока специальностей.
    private static function getReceptionDuration($specialtyId)
    {
        // Проверка наличия ID специальности. Если ID не передан или равен 0/null,
        // метод немедленно возвращает null (длительность неизвестна).
        if (!$specialtyId) return null;
        
        // Получение значения свойства 'RECEPTION_DURATION' (длительность приёма) 
        // для элемента специальности. SPECIALTIES_IBLOCK_ID - константа с ID инфоблока специальностей.
        $rs = \CIBlockElement::GetProperty(
            SPECIALTIES_IBLOCK_ID, 
            $specialtyId, 
            [], 
            ['CODE' => 'RECEPTION_DURATION']
        );
        
        // Извлечение первого (и единственного) значения свойства.
        if ($prop = $rs->Fetch()) {
            // Преобразование значения в целое число функцией intval.
            // Свойство в Битрикс хранится как строка, поэтому требуется явное приведение типа.
            return intval($prop['VALUE']);
        }
        
        // Если свойство не найдено или не заполнено, возвращается null.
        return null;
    }

    // Объявление приватного статического метода getSpecialtyName. Метод получает 
    // название специальности по её ID для отображения в сообщениях об ошибках.
    private static function getSpecialtyName($specialtyId)
    {
        // Проверка наличия ID. Если ID не передан, возвращается строка 'неизвестно'.
        if (!$specialtyId) return 'неизвестно';
        
        // Использование современного ORM API Битрикс (D7) для получения данных элемента.
        // ElementTable - это класс таблицы элементов инфоблоков.
        $elem = ElementTable::getRow([
            // Параметр 'select' определяет, какие поля выбрать. Здесь нужно только название.
            'select' => ['NAME'],
            
            // Параметр 'filter' задаёт условия фильтрации: элемент с указанным ID 
            // из инфоблока специальностей.
            'filter' => ['ID' => $specialtyId, 'IBLOCK_ID' => SPECIALTIES_IBLOCK_ID]
        ]);
        
        // Тернарный оператор ? : возвращает $elem['NAME'], если $elem не null (элемент найден),
        // иначе возвращает строку 'неизвестно'.
        return $elem ? $elem['NAME'] : 'неизвестно';
    }
