// Директива use импортирует класс Loader из пространства имен Bitrix\Main
// Класс Loader отвечает за подключение модулей 1С-Битрикс
use Bitrix\Main\Loader;

// Директива use импортирует класс IblockTable из пространства имен Bitrix\Iblock
// Класс IblockTable предоставляет ORM-интерфейс для работы с инфоблоками (таблица b_iblock)
use Bitrix\Iblock\IblockTable;

// Вызов встроенной PHP-функции spl_autoload_register()
// Функция регистрирует пользовательскую функцию автозагрузки классов
// Параметром передается анонимная функция (замыкание/closure) с аргументом $class
spl_autoload_register(function ($class) {
    
    // Объявление переменной $prefix и присвоение строкового значения 'Local\\'
    // Это префикс пространства имен, за который отвечает наш автозагрузчик
    // Двойной обратный слеш экранирован для PHP-строки
    $prefix = 'Local\\';
    
    // Объявление переменной $base_dir
    // Конкатенация $_SERVER['DOCUMENT_ROOT'] (корень сайта) с путем '/local/lib/'
    // Получаем абсолютный путь к директории с классами: /var/www/site/local/lib/
    $base_dir = $_SERVER['DOCUMENT_ROOT'] . '/local/lib/';
    
    // Вызов функции strlen() с аргументом $prefix
// Функция возвращает длину строки в байтах (количество символов)
// Результат сохраняется в переменную $len (для 'Local\\' это 6 символов)
    $len = strlen($prefix);
    
    // Вызов функции strncmp() для сравнения строк с ограничением длины
    // Параметры: $prefix (эталон), $class (проверяемый класс), $len (сколько символов сравнивать)
    // Функция возвращает 0 если строки идентичны, иначе отрицательное/положительное число
    // Оператор !== (не идентично) проверяет что результат НЕ равен 0
    // Условие: если класс НЕ начинается с 'Local\\', выполняем return и прекращаем автозагрузку
    if (strncmp($prefix, $class, $len) !== 0) return;
    
    // Вызов функции substr() для извлечения подстроки
    // Параметры: $class (исходная строка), $len (начальная позиция - пропускаем префикс)
    // Получаем относительное имя класса без префикса: 'CustomProperties\DoctorProperty'
    $relative_class = substr($class, $len);
    
    // Конкатенация нескольких строк для формирования пути к файлу
    // $base_dir - базовая директория (/var/www/site/local/lib/)
    // str_replace('\\', '/', $relative_class) - заменяем обратные слеши на прямые для совместимости с Windows/Unix
    // '.php' - расширение файла
    // Результат: /var/www/site/local/lib/CustomProperties/DoctorProperty.php
    $file = $base_dir . str_replace('\\', '/', $relative_class) . '.php';
    
    // Вызов функции file_exists() проверяет существование файла по указанному пути
    // Возвращает true если файл существует и доступен для чтения
    // Условный оператор if выполняет следующую инструкцию только при true
    if (file_exists($file)) require $file;
    
// Закрывающая фигурная скобка анонимной функции автозагрузки
// Круглая скобка закрывает вызов spl_autoload_register
});

// Вызов функции define() для создания константы
// Параметры: 'DOCTORS_IBLOCK_ID' (имя константы), 16 (целочисленное значение)
// Константа хранит ID инфоблока "Врачи" для использования во всем коде
define('DOCTORS_IBLOCK_ID', 16);

// Вызов функции define() для создания второй константы
// Параметры: 'SPECIALTIES_IBLOCK_ID' (имя), 17 (значение)
// Константа хранит ID инфоблока "Специальности"
define('SPECIALTIES_IBLOCK_ID', 17);

// Вызов статического метода includeModule() класса Loader
// Класс Loader загружен через use в начале файла
// Параметр 'iblock' - строковой идентификатор модуля инфоблоков
// Метод подключает модуль инфоблоков, необходимый для работы с IblockTable
Loader::includeModule('iblock');

// Вызов статического метода getRow() класса IblockTable
// Метод возвращает одну строку из таблицы инфоблоков по фильтру
// Параметр - массив с настройками запроса
$bookingIblock = IblockTable::getRow([
    
    // Ключ 'select' массива определяет какие поля выбирать из БД
    // Значение - массив с именем поля ['ID']
    // Выбираем только ID инфоблока для экономии ресурсов
    'select' => ['ID'],
    
    // Ключ 'filter' массива задает условия фильтрации WHERE в SQL
    // Значение - массив с условием ['=CODE' => 'booking']
    // Оператор '=' означает точное равенство
    // Ищем инфоблок с символьным кодом 'booking'
    'filter' => ['=CODE' => 'booking']
    
// Закрывающая квадратная скобка массива параметров
// Закрывающая круглая скобка вызова метода getRow()
]);

// Вызов функции define() для создания константы BOOKING_IBLOCK_ID
// Тернарный оператор ? : проверяет условие и возвращает одно из двух значений
// Условие: $bookingIblock (проверка на непустой массив/не null)
// Если true: (int)$bookingIblock['ID'] - приводим ID к целому числу
// Если false: 0 - значение по умолчанию если инфоблок не найден
define('BOOKING_IBLOCK_ID', $bookingIblock ? (int)$bookingIblock['ID'] : 0);

// Вызов функции AddEventHandler() - API 1С-Битрикс для подписки на события
// Параметр 1: "iblock" - идентификатор модуля, генерирующего событие
// Параметр 2: "OnIBlockPropertyBuildList" - строковой код события
// Событие вызывается при построении списка типов свойств инфоблока
// Параметр 3: ['Local\CustomProperties\DoctorProperty', 'getTypeDescription']
// Массив с callable: класс и статический метод, который вернет описание типа свойства
// Метод getTypeDescription должен вернуть массив с ключами: PROPERTY_TYPE, USER_TYPE, DESCRIPTION
AddEventHandler("iblock", "OnIBlockPropertyBuildList", ['Local\CustomProperties\DoctorProperty', 'getTypeDescription']);

// Вызов функции AddEventHandler() для регистрации второго обработчика
// Аналогично предыдущему вызову, но для класса SpecialtyProperty
// Регистрирует кастомный тип свойства "Привязка к специальности"
AddEventHandler("iblock", "OnIBlockPropertyBuildList", ['Local\CustomProperties\SpecialtyProperty', 'getTypeDescription']);

// Вызов функции AddEventHandler() для события перед добавлением элемента
// "OnBeforeIBlockElementAdd" - событие срабатывает перед INSERT в базу данных
// Обработчик BookingHandlers::onBeforeAdd выполняет валидацию данных бронирования
// Проверяет что выбранное время не занято другой записью
AddEventHandler("iblock", "OnBeforeIBlockElementAdd", ['Local\CustomProperties\BookingHandlers', 'onBeforeAdd']);

// Вызов функции AddEventHandler() для события перед обновлением элемента
// "OnBeforeIBlockElementUpdate" - событие срабатывает перед UPDATE в БД
// Обработчик BookingHandlers::onBeforeUpdate проверяет конфликты при изменении записи
// Предотвращает перезапись существующего бронирования
AddEventHandler("iblock", "OnBeforeIBlockElementUpdate", ['Local\CustomProperties\BookingHandlers', 'onBeforeUpdate']);

// Вызов функции AddEventHandler() для серверной автонумерации (резервный вариант)
// Параметр 3 - анонимная функция, принимающая массив полей по ссылке (&$arFields)
// Передача по ссылке (&) позволяет модифицировать массив внутри функции
AddEventHandler("iblock", "OnBeforeIBlockElementAdd", function(&$arFields) {
    
    // Условный оператор if с тремя проверками, объединенными оператором &&
    // Проверка 1: $arFields['IBLOCK_ID'] == BOOKING_IBLOCK_ID
    //   Оператор == сравнивает значения без учета типа (равенство)
    //   Проверяем что элемент создается в инфоблоке бронирования
    // Проверка 2: empty($arFields['NAME'])
    //   Функция empty() возвращает true если переменная не существует, null, '', 0, false, []
    //   Проверяем что поле названия пустое и требует автозаполнения
    // Обе проверки должны быть истинны для выполнения блока кода
    if ($arFields['IBLOCK_ID'] == BOOKING_IBLOCK_ID && empty($arFields['NAME'])) {
        
        // Создание объекта CIBlockElement - класс API для работы с элементами инфоблоков
        // Оператор new выделяет память и вызывает конструктор класса
        // CIBlockElement предоставляет методы GetList, Add, Update, Delete
        $rs = CIBlockElement::GetList(
            
            // Параметр 1: массив сортировки ['ID' => 'DESC']
            // Ключ 'ID' - поле сортировки
            // Значение 'DESC' - по убыванию (сначала новые/большие ID)
            ['ID' => 'DESC'],
            
            // Параметр 2: массив фильтра ['IBLOCK_ID' => BOOKING_IBLOCK_ID]
            // Отбираем только элементы из инфоблока бронирования
            ['IBLOCK_ID' => BOOKING_IBLOCK_ID],
            
            // Параметр 3: false - параметр группировки (не используется)
            false,
            
            // Параметр 4: массив навигации ['nTopCount' => 1]
            // 'nTopCount' ограничивает выборку указанным количеством записей
            // Значение 1 - достаточно получить только один элемент с максимальным ID
            ['nTopCount' => 1],
            
            // Параметр 5: массив выбираемых полей ['ID']
            // Указываем что нужно только поле ID для экономии ресурсов
            ['ID']
            
        // Закрывающие скобки вызова метода GetList
        );
        
        // Вызов метода Fetch() объекта CIBlockResult (хранится в $rs)
        // Метод извлекает следующую строку результата в виде массива
        // Оператор ?? (null coalescing operator, PHP 7+) возвращает левый операнд если он существует и не null
        // Иначе возвращает правый операнд (0)
        // Результат: максимальный ID или 0 если таблица пуста
        $maxId = $rs->Fetch()['ID'] ?? 0;
        
        // Присвоение значения элементу массива $arFields по ключу 'NAME'
        // Конкатенация строк: "Бронирование № " + ($maxId + 1)
        // Оператор + выполняет арифметическое сложение с приведением типов
        // Формируем название элемента для сохранения в БД
        $arFields['NAME'] = "Бронирование № " . ($maxId + 1);
        
    // Закрывающая фигурная скобка условного оператора if
    }
    
// Закрывающая фигурная скобка анонимной функции
// Круглая скобка закрывает вызов AddEventHandler
});

// Многострочный комментарий DocBlock для документирования функции
// Описывает назначение следующего блока кода - автонумерация через JS
/**
 * Автонумерация при открытии формы - через OnEndBufferContent
 */

// Вызов AddEventHandler() для события "main" (ядро) "OnBeforeProlog"
// Событие срабатывает в начале работы страницы, перед подключением header.php
// Используем его для регистрации второго обработчика с нужным контекстом
AddEventHandler("main", "OnBeforeProlog", function() {
    
    // Вложенный вызов AddEventHandler() внутри первого обработчика
    // "OnEndBufferContent" - событие перед выводом буфера (после формирования всего HTML)
    // Позволяет модифицировать финальный HTML через параметр &$content (передача по ссылке)
    AddEventHandler("main", "OnEndBufferContent", function(&$content) {
        
        // Присвоение переменной $requestUri значения из суперглобального массива $_SERVER
        // Оператор ?? (null coalescing) возвращает пустую строку если ключ не существует
        // $_SERVER['REQUEST_URI'] содержит путь текущей страницы (например, /services/lists/18/element/0/)
        $requestUri = $_SERVER['REQUEST_URI'] ?? '';
        
        // Условный оператор if с функцией preg_match()
        // preg_match() выполняет проверку строки по регулярному выражению PCRE
        // Параметр 1: шаблон '/\/services\/lists\/' . BOOKING_IBLOCK_ID . '\/element\/0\//'
        //   \/ - экранированный слеш (разделитель в regex)
        //   services/lists/ - статическая часть пути
        //   BOOKING_IBLOCK_ID - подстановка константы через конкатенацию точками
        //   /element/0/ - шаблон страницы создания нового элемента (ID=0)
        // Параметр 2: $requestUri - проверяемая строка
        // Возвращает 1 при совпадении, 0 при несовпадении, false при ошибке
        // Оператор ! инвертирует результат: если НЕ совпадает - выходим
        if (!preg_match('/\/services\/lists\/' . BOOKING_IBLOCK_ID . '\/element\/0\//', $requestUri)) {
            
            // Оператор return прекращает выполнение функции
            // Если это не страница создания бронирования - не вставляем JS
            return;
            
        // Закрывающая фигурная скобка условия if
        }
        
        // Инициализация переменной $maxId значением 0
        // Тип integer, начальное значение для поиска максимального ID
        $maxId = 0;
        
        // Создание объекта CIBlockElement для запроса к базе данных
        // Используется старый API без ORM для совместимости
        $rs = CIBlockElement::GetList(
            
            // Массив сортировки: по полю ID в порядке убывания (DESCending)
            // Сначала идут элементы с наибольшими ID
            ['ID' => 'DESC'],
            
            // Массив фильтра: отбираем только элементы инфоблока бронирования
            // BOOKING_IBLOCK_ID подставляется из константы
            ['IBLOCK_ID' => BOOKING_IBLOCK_ID],
            
            // Параметр группировки - false (не группировать)
            false,
            
            // Массив ограничений выборки: nTopCount => 1 (только 1 запись)
            // Достаточно получить элемент с максимальным ID
            ['nTopCount' => 1],
            
            // Массив выбираемых полей: только ID
            ['ID']
            
        // Закрывающие скобки вызова GetList
        );
        
        // Условный оператор if проверяет результат присваивания
        // Выражение $el = $rs->Fetch() присваивает в $el массив данных или false
        // Если Fetch() вернул массив (не пустая выборка) - условие истинно
        if ($el = $rs->Fetch()) {
            
            // Присвоение переменной $maxId с приведением типа (int)
            // Берем значение ID из массива $el и конвертируем в целое число
            // Защита от строковых ID, хотя в Битрикс ID обычно integer
            $maxId = (int)$el['ID'];
            
        // Закрывающая фигурная скобка условия if
        }
        
        // Арифметическая операция сложения: $maxId + 1
        // Получаем следующий номер для автонумерации
        // Результат сохраняется в переменную $nextNumber
        $nextNumber = $maxId + 1;
        
        // Конкатенация строки 'Бронирование № ' с числом $nextNumber
        // PHP автоматически приводит число к строке при конкатенации точкой
        // Результат: строка для подстановки в поле NAME формы
        $defaultValue = 'Бронирование № ' . $nextNumber;
        
        // Начало формирования строки с JavaScript кодом
        // Используется HEREDOC-синтаксис с идентификатором <script type="text/javascript">
        // Позволяет вставлять многострочный код без экранирования кавычек
        $js = '<script type="text/javascript">
        
        // Начало Immediately Invoked Function Expression (IIFE)
        // (function() { ... })() - создает изолированную область видимости
        // Предотвращает конфликты переменных с глобальным пространством имен
        (function() {
            
            // Объявление именованной функции setBookingName внутри IIFE
            // Функция ищет поле ввода NAME и устанавливает значение по умолчанию
            function setBookingName() {
                
                // Вызов метода document.querySelector() DOM API
                // Параметр: строка CSS-селектора \'input[name="NAME"]\'
                // Ищет первый input элемент с атрибутом name равным "NAME"
                // Возвращает DOM-элемент или null если не найден
                var input = document.querySelector(\'input[name="NAME"]\');
                
                // Условный оператор if с логическим НЕ (!)
                // Проверяет что input равен null (элемент не найден через querySelector)
                // querySelector может не сработать если структура DOM изменена
                if (!input) {
                    
                    // Получение HTMLCollection через document.getElementsByTagName("input")
                    // Возвращает живую коллекцию всех input элементов на странице
                    var inputs = document.getElementsByTagName("input");
                    
                    // Цикл for с тремя выражениями
                    // Инициализация: var i = 0 (счетчик)
                    // Условие: i < inputs.length (пока не дойдем до конца коллекции)
                    // Инкремент: i++ (увеличение на 1 после каждой итерации)
                    for (var i = 0; i < inputs.length; i++) {
                        
                        // Условие if проверяет свойство name текущего элемента
                        // inputs[i] - доступ к элементу по индексу (квадратные скобки)
                        // Оператор === строгое равенство (тип и значение)
                        // Сравниваем с строкой "NAME"
                        if (inputs[i].name === "NAME") {
                            
                            // Присвоение найденного элемента переменной input
                            input = inputs[i];
                            
                            // Оператор break прерывает выполнение цикла for
                            // Нашли нужный элемент - дальше искать не нужно
                            break;
                            
                        // Закрывающая фигурная скобка условия if
                        }
                        
                    // Закрывающая фигурная скобка цикла for
                    }
                    
                // Закрывающая фигурная скобка условия if (!input)
                }
                
                // Условный оператор if с двумя проверками через &&
