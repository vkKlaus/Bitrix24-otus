        // Параметр 1: '</body>' - что искать (закрывающий тег body)
        // Параметр 2: $js - чем заменять (наш скрипт + закрывающий body)
        // Параметр 3: $content - где искать (ссылка на буфер вывода)
        // Результат присваивается обратно в $content (модификация по ссылке)
        $content = str_replace('</body>', $js, $content);
        
