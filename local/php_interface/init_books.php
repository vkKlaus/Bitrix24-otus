                    // Параметр 1: функция, которая сбрасывает фоновый цвет
                    // Параметр 2: 1000 миллисекунд (1 секунда задержки)
                    // Через 1 секунду поле вернется к стандартному виду
                    setTimeout(function() { input.style.backgroundColor = ""; }, 1000);
                    
