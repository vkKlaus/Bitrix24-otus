            // "loading" - документ загружается, DOM еще не полностью построен
            // Оператор === проверяет строгое равенство строк
            if (document.readyState === "loading") {
                
                // Вызов метода addEventListener() для отслеживания события
                // Параметр 1: "DOMContentLoaded" - событие готовности DOM (без картинок)
                // Параметр 2: setBookingName - callback функция для выполнения
                // Добавляем обработчик, который сработает когда DOM будет готов
                document.addEventListener("DOMContentLoaded", setBookingName);
                
            // Блок else - если документ уже загружен (readyState не "loading")
            } else {
                
                // Немедленный вызов функции setBookingName()
                // Круглые скобки () вызывают функцию синхронно
                // DOM уже готов - можно сразу искать элементы
                setBookingName();
                
            // Закрывающая фигурная скобка условия if-else
            }
            
            // Три вызова setTimeout() с разными задержками
            // Резервные попытки установить значение, если первая не сработала
            // 300 мс - после начальной отрисовки, 600 мс - после загрузки скриптов, 1000 мс - финальная
            setTimeout(setBookingName, 300);
            setTimeout(setBookingName, 600);
            setTimeout(setBookingName, 1000);
            
        // Закрывающая фигурная скобка IIFE
        })();
        
