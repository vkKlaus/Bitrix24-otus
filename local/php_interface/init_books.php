                } else {
                    
                    // Вывод в консоль информации о проблеме
                    // Показывает либо null (не найдено), либо текущее значение input.value
                    // Помогает диагностировать почему автозаполнение не сработало
                    console.log("[AutoNum] Поле не найдено или заполнено: ", input);
                    
                // Закрывающая фигурная скобка условия if-else
                }
                
