// Оператор if — условный оператор, проверяет истинность выражения в скобках
// Функция file_exists() — встроенная PHP-функция, проверяет существование файла
// по указанному пути на файловой системе сервера, возвращает true если файл есть
// или false если файл отсутствует или недоступен для чтения
// __DIR__ — магическая константа PHP, содержит абсолютный путь к директории,
// в которой расположен текущий исполняемый файл (init.php)
// Оператор конкатенации точка (.) — объединяет строки: путь + '/classes/autoload.php'
// Получается полный путь: /local/php_interface/classes/autoload.php
if (file_exists(__DIR__ . '/classes/autoload.php'))
{
    // Тело условия выполняется только если file_exists вернул true
    
    // Конструкция require_once — оператор включения файла в PHP
    // require — включает и выполняет указанный файл, генерирует фатальную ошибку E_COMPILE_ERROR,
    // если файл не найден (в отличие от include, который выдаёт только предупреждение)
    // _once — модификатор, гарантирующий что файл будет подключён только один раз,
    // даже если require_once вызван несколько раз (предотвращает повторное объявление классов/функций)
    // __DIR__ . '/classes/autoload.php' — тот же путь, что проверяли выше
    // autoload.php обычно содержит spl_autoload_register() — регистрацию функции автозагрузки,
    // которая автоматически подключает файлы классов при их первом использовании
    require_once __DIR__ . '/classes/autoload.php';
}

